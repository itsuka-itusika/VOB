export function getCaptiveConversationLines(captive, { failed = false } = {}) {
  const mindTraits = Array.isArray(captive?.mindTraits) ? captive.mindTraits : [];
  // 狂信は懐柔・誘惑の成功率が0のため、失敗状態より優先して「揺るがない」ことを示す。
  if (mindTraits.includes("狂信")) {
    return CAPTIVE_CONVERSATION_LINES["狂信"];
  }
  if (failed) {
    return ["こちらの言葉に目を伏せ、今月はもう口を開きそうにない。"];
  }
  const type = String(captive?.raiderType || captive?.job || captive?.race || "");
  return CAPTIVE_CONVERSATION_LINES[CAPTIVE_TYPE_KEYS[type]] || CAPTIVE_CONVERSATION_LINES.default;
}
