export function getDespairDepartureLine(character) {
  const tone = resolveDialogueTone(character);
  const key = getToneLookupKeys(tone, character).find(candidate => DESPAIR_DEPARTURE_LINES[candidate]);
  const lines = DESPAIR_DEPARTURE_LINES[key] || DESPAIR_DEPARTURE_LINES.default;
  return lines[Math.floor(Math.random() * lines.length)];
}